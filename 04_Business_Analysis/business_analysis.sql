-- 1. Calculate total revenue from delivered orders

SELECT SUM(OD.QUANTITY * OD.UNIT_PRICE - OD.DISCOUNT_AMOUNT)
       AS TOTAL_REVENUE
FROM ORDER_DETAILS OD
JOIN ORDERS O ON OD.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS = 'Delivered';


-- 2. Count total delivered orders

SELECT COUNT(*) AS TOTAL_DELIVERED_ORDERS
FROM ORDERS
WHERE ORDER_STATUS = 'Delivered';


-- 3. Find total quantity of products sold

SELECT SUM(OD.QUANTITY) AS TOTAL_UNITS_SOLD
FROM ORDER_DETAILS OD
JOIN ORDERS O ON OD.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS = 'Delivered';


-- 4. Calculate estimated gross profit

SELECT SUM(
    OD.QUANTITY * (OD.UNIT_PRICE - P.COST_PRICE)
    - OD.DISCOUNT_AMOUNT
) AS ESTIMATED_GROSS_PROFIT
FROM ORDER_DETAILS OD
JOIN PRODUCTS P ON OD.PRODUCT_ID = P.PRODUCT_ID
JOIN ORDERS O ON OD.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS = 'Delivered';


-- 5. Calculate average order value

SELECT AVG(ORDER_TOTAL) AS AVERAGE_ORDER_VALUE
FROM (
    SELECT O.ORDER_ID,
           SUM(OD.QUANTITY * OD.UNIT_PRICE
               - OD.DISCOUNT_AMOUNT) AS ORDER_TOTAL
    FROM ORDERS O
    JOIN ORDER_DETAILS OD ON O.ORDER_ID = OD.ORDER_ID
    WHERE O.ORDER_STATUS = 'Delivered'
    GROUP BY O.ORDER_ID
);


-- 6. Find the number of orders by payment method

SELECT PAYMENT_METHOD, COUNT(*) AS TOTAL_ORDERS
FROM ORDERS
GROUP BY PAYMENT_METHOD;


-- 7. Count orders by their status

SELECT ORDER_STATUS, COUNT(*) AS TOTAL_ORDERS
FROM ORDERS
GROUP BY ORDER_STATUS;


-- 8. Find the highest-priced product

SELECT PRODUCT_NAME, UNIT_PRICE
FROM PRODUCTS
WHERE UNIT_PRICE = (SELECT MAX(UNIT_PRICE) FROM PRODUCTS);


-- 9. Find the cheapest product

SELECT PRODUCT_NAME, UNIT_PRICE
FROM PRODUCTS
WHERE UNIT_PRICE = (SELECT MIN(UNIT_PRICE) FROM PRODUCTS);


-- 10. Find the number of customers in each city

SELECT CITY, COUNT(*) AS TOTAL_CUSTOMERS
FROM CUSTOMERS
GROUP BY CITY
ORDER BY TOTAL_CUSTOMERS DESC;


-- 11. Find total orders by customer city

SELECT C.CITY, COUNT(O.ORDER_ID) AS TOTAL_ORDERS
FROM CUSTOMERS C
JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY C.CITY
ORDER BY TOTAL_ORDERS DESC;


-- 12. Identify products with low stock (less than 30)

SELECT PRODUCT_NAME, STOCK_QUANTITY
FROM PRODUCTS
WHERE STOCK_QUANTITY < 30;


-- 13. Find products with selling price above 50000

SELECT PRODUCT_NAME, UNIT_PRICE
FROM PRODUCTS
WHERE UNIT_PRICE > 50000
ORDER BY UNIT_PRICE DESC;


-- 14. Calculate total discounts on delivered orders

SELECT SUM(OD.DISCOUNT_AMOUNT) AS TOTAL_DISCOUNT
FROM ORDER_DETAILS OD
JOIN ORDERS O ON OD.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS = 'Delivered';


-- 15. Find customers who placed more than one order

SELECT C.CUSTOMER_NAME, COUNT(O.ORDER_ID) AS TOTAL_ORDERS
FROM CUSTOMERS C
JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
HAVING COUNT(O.ORDER_ID) > 1;


-- 16. Calculate revenue by product category

SELECT CAT.CATEGORY_NAME,
       SUM(OD.QUANTITY * OD.UNIT_PRICE
           - OD.DISCOUNT_AMOUNT) AS TOTAL_REVENUE
FROM CATEGORIES CAT
JOIN PRODUCTS P ON CAT.CATEGORY_ID = P.CATEGORY_ID
JOIN ORDER_DETAILS OD ON P.PRODUCT_ID = OD.PRODUCT_ID
JOIN ORDERS O ON OD.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS = 'Delivered'
GROUP BY CAT.CATEGORY_NAME
ORDER BY TOTAL_REVENUE DESC;


-- 17. Calculate revenue by city

SELECT C.CITY,
       SUM(OD.QUANTITY * OD.UNIT_PRICE
           - OD.DISCOUNT_AMOUNT) AS TOTAL_REVENUE
FROM CUSTOMERS C
JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
JOIN ORDER_DETAILS OD ON O.ORDER_ID = OD.ORDER_ID
WHERE O.ORDER_STATUS = 'Delivered'
GROUP BY C.CITY
ORDER BY TOTAL_REVENUE DESC;


-- 18. Find total spending by each customer

SELECT C.CUSTOMER_NAME,
       SUM(OD.QUANTITY * OD.UNIT_PRICE
           - OD.DISCOUNT_AMOUNT) AS TOTAL_SPENDING
FROM CUSTOMERS C
JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
JOIN ORDER_DETAILS OD ON O.ORDER_ID = OD.ORDER_ID
WHERE O.ORDER_STATUS = 'Delivered'
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
ORDER BY TOTAL_SPENDING DESC;


-- 19. Calculate monthly revenue

SELECT TO_CHAR(O.ORDER_DATE, 'MON-YYYY') AS MONTH,
       SUM(OD.QUANTITY * OD.UNIT_PRICE
           - OD.DISCOUNT_AMOUNT) AS MONTHLY_REVENUE
FROM ORDERS O
JOIN ORDER_DETAILS OD ON O.ORDER_ID = OD.ORDER_ID
WHERE O.ORDER_STATUS = 'Delivered'
GROUP BY TRUNC(O.ORDER_DATE, 'MM'),
         TO_CHAR(O.ORDER_DATE, 'MON-YYYY')
ORDER BY TRUNC(O.ORDER_DATE, 'MM');


-- 20. Find products that have never been ordered

SELECT P.PRODUCT_NAME
FROM PRODUCTS P
WHERE NOT EXISTS (
    SELECT 1
    FROM ORDER_DETAILS OD
    WHERE OD.PRODUCT_ID = P.PRODUCT_ID
);


-- 21. Calculate the cancellation rate

SELECT
    ROUND(
        SUM(CASE WHEN ORDER_STATUS = 'Cancelled' THEN 1 ELSE 0 END)
        * 100 / COUNT(*), 2
    ) AS CANCELLATION_RATE
FROM ORDERS;


-- 22. Find the top 10 best-selling products by quantity

SELECT P.PRODUCT_NAME,
       SUM(OD.QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM PRODUCTS P
JOIN ORDER_DETAILS OD ON P.PRODUCT_ID = OD.PRODUCT_ID
JOIN ORDERS O ON OD.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS = 'Delivered'
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
ORDER BY TOTAL_QUANTITY_SOLD DESC
FETCH FIRST 10 ROWS ONLY;


-- 23. Find the product generating the highest revenue

SELECT P.PRODUCT_NAME,
       SUM(OD.QUANTITY * OD.UNIT_PRICE
           - OD.DISCOUNT_AMOUNT) AS TOTAL_REVENUE
FROM PRODUCTS P
JOIN ORDER_DETAILS OD ON P.PRODUCT_ID = OD.PRODUCT_ID
JOIN ORDERS O ON OD.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS = 'Delivered'
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
ORDER BY TOTAL_REVENUE DESC
FETCH FIRST 1 ROW ONLY;


-- 24. Calculate average order value by payment method

SELECT PAYMENT_METHOD,
       AVG(ORDER_TOTAL) AS AVERAGE_ORDER_VALUE
FROM (
    SELECT O.ORDER_ID,
           O.PAYMENT_METHOD,
           SUM(OD.QUANTITY * OD.UNIT_PRICE
               - OD.DISCOUNT_AMOUNT) AS ORDER_TOTAL
    FROM ORDERS O
    JOIN ORDER_DETAILS OD ON O.ORDER_ID = OD.ORDER_ID
    WHERE O.ORDER_STATUS = 'Delivered'
    GROUP BY O.ORDER_ID, O.PAYMENT_METHOD
)
GROUP BY PAYMENT_METHOD;


-- 25. Find the product with the highest profit per unit

SELECT PRODUCT_NAME,
       (UNIT_PRICE - COST_PRICE) AS PROFIT_PER_UNIT
FROM PRODUCTS
WHERE (UNIT_PRICE - COST_PRICE) =
      (SELECT MAX(UNIT_PRICE - COST_PRICE) FROM PRODUCTS);


-- 26. Find the category containing the most products

SELECT CAT.CATEGORY_NAME,
       COUNT(P.PRODUCT_ID) AS TOTAL_PRODUCTS
FROM CATEGORIES CAT
JOIN PRODUCTS P ON CAT.CATEGORY_ID = P.CATEGORY_ID
GROUP BY CAT.CATEGORY_ID, CAT.CATEGORY_NAME
ORDER BY TOTAL_PRODUCTS DESC
FETCH FIRST 1 ROW ONLY;


-- 27. Analyse monthly order trends

SELECT TO_CHAR(ORDER_DATE, 'MON-YYYY') AS MONTH,
       COUNT(*) AS TOTAL_ORDERS
FROM ORDERS
GROUP BY TRUNC(ORDER_DATE, 'MM'),
         TO_CHAR(ORDER_DATE, 'MON-YYYY')
ORDER BY TRUNC(ORDER_DATE, 'MM');


-- 28. Find customers who have never placed an order

SELECT CUSTOMER_NAME
FROM CUSTOMERS C
WHERE NOT EXISTS (
    SELECT 1
    FROM ORDERS O
    WHERE O.CUSTOMER_ID = C.CUSTOMER_ID
);


-- 29. Find the highest-value individual order

SELECT O.ORDER_ID,
       SUM(OD.QUANTITY * OD.UNIT_PRICE
           - OD.DISCOUNT_AMOUNT) AS ORDER_VALUE
FROM ORDERS O
JOIN ORDER_DETAILS OD ON O.ORDER_ID = OD.ORDER_ID
GROUP BY O.ORDER_ID
ORDER BY ORDER_VALUE DESC
FETCH FIRST 1 ROW ONLY;


-- 30. Find products with estimated profit below 500 per unit

SELECT PRODUCT_NAME,
       (UNIT_PRICE - COST_PRICE) AS PROFIT_PER_UNIT
FROM PRODUCTS
WHERE (UNIT_PRICE - COST_PRICE) < 500
ORDER BY PROFIT_PER_UNIT;


